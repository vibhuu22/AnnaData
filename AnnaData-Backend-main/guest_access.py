"""
Questions from someone who has not signed in yet.

The web app used to demand a phone number and a one-time code before a farmer
had seen a single answer. That is the most expensive thing the app can ask -
it costs an SMS off our own SIM and a minute of the farmer's attention - and it
was asked before there was any reason to trust us with it. So a farmer now asks
first, sees it work, and confirms their number only when they choose to save
their farm.

That opens an unauthenticated endpoint which spends model quota on every call,
which is precisely what the sign-in work closed. Three bounds keep it closed in
the way that matters:

  per guest   A browser's own id. Stops one person asking forever, and it is the
              limit a real farmer actually meets - so its refusal is phrased as
              an invitation to sign in, not as an error.
  per address Guest ids are generated by the browser and trivially rotated, so
              they bound nobody hostile. The network address does. It is set
              deliberately loose: Indian mobile carriers put whole villages
              behind one address (carrier-grade NAT), and a tight limit here
              would turn away every farmer on a Jio tower because one of them
              was curious.
  per day     A ceiling on all guest questions together, so the worst case for
              the model bill is a number someone chose rather than whatever an
              attacker can afford.

Counts are kept in this process's memory. Cloud Run runs up to three instances
and each keeps its own, so the effective limits are up to three times these
figures and reset on a restart. That is fine for bounding abuse; it would not be
fine for billing, and nothing here pretends otherwise.

A guest's messages are stored under `guest:<uuid>` - a key that can never be
mistaken for a phone number, so a guest can never read or write a real farmer's
profile, and the rating scheduler (which only ever messages digit-only ids)
cannot text one. When the guest confirms a number, profile_store.claim_guest
moves the conversation onto it.
"""
import math
import re
import threading
import time
from collections import deque

GUEST_PREFIX = "guest:"

# A version-4 UUID, which is what crypto.randomUUID() produces in the browser.
# Strict on purpose: this string becomes a database key, and a guest id that
# could carry a colon, a plus sign or a phone number's digits would be a way to
# write into somebody else's row.
_UUID4 = re.compile(
    r"^[0-9a-f]{8}-[0-9a-f]{4}-4[0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$"
)


def guest_user_id(raw: str | None) -> str | None:
    """The storage key for a browser-supplied guest id, or None if it is not one."""
    value = (raw or "").strip().lower()
    if not _UUID4.match(value):
        return None
    return GUEST_PREFIX + value


def is_guest(user_id: str | None) -> bool:
    return bool(user_id) and user_id.startswith(GUEST_PREFIX)


def client_ip(forwarded_for: str | None, peer: str | None) -> str:
    """The caller's address as Cloud Run reports it.

    Cloud Run's front end appends the real client to X-Forwarded-For, so the
    first entry is the browser. Without the header (local development) the
    socket's own peer is the best available.
    """
    if forwarded_for:
        first = forwarded_for.split(",")[0].strip()
        if first:
            return first
    return (peer or "unknown").strip() or "unknown"


class _Window:
    """Timestamps of past events for one key, oldest first."""

    __slots__ = ("events",)

    def __init__(self):
        self.events = deque()


class GuestLimiter:
    """Three sliding windows, checked together and recorded together.

    A question is admitted only if every window has room, and is counted in all
    of them or none. Counting a refused question would let a farmer who hit the
    hourly limit lock themselves out further by retrying.
    """

    def __init__(self, per_guest: int, per_ip: int, daily_cap: int,
                 window_seconds: int = 3600, clock=time.monotonic):
        self.per_guest = per_guest
        self.per_ip = per_ip
        self.daily_cap = daily_cap
        self.window = window_seconds
        self.clock = clock
        self._lock = threading.Lock()
        self._guests: dict[str, _Window] = {}
        self._ips: dict[str, _Window] = {}
        self._all = _Window()

    @staticmethod
    def _wait(win: _Window, limit: int, span: int, now: float) -> int:
        """Seconds until `win` has room for one more, 0 if it has room now."""
        while win.events and now - win.events[0] >= span:
            win.events.popleft()
        if limit <= 0:
            return span
        if len(win.events) < limit:
            return 0
        # The oldest event leaves the window at exactly `span` after it.
        return max(1, math.ceil(span - (now - win.events[0])))

    def check(self, guest: str, ip: str) -> tuple[bool, int, str]:
        """(admitted, retry_after_seconds, which_limit). Records only if admitted."""
        now = self.clock()
        with self._lock:
            g = self._guests.setdefault(guest, _Window())
            a = self._ips.setdefault(ip, _Window())

            for win, limit, span, name in (
                (g, self.per_guest, self.window, "guest"),
                (a, self.per_ip, self.window, "address"),
                (self._all, self.daily_cap, 86400, "daily"),
            ):
                wait = self._wait(win, limit, span, now)
                if wait:
                    return False, wait, name

            for win in (g, a, self._all):
                win.events.append(now)

            # Forget keys that have gone quiet, so a month of distinct guests
            # does not become a month of dictionary entries.
            if len(self._guests) > 5000:
                self._prune(self._guests, now)
            if len(self._ips) > 5000:
                self._prune(self._ips, now)
        return True, 0, ""

    def _prune(self, table: dict, now: float) -> None:
        for key in [k for k, w in table.items()
                    if not w.events or now - w.events[-1] >= self.window]:
            del table[key]


# What the farmer reads when a limit is reached. The guest limit is the one a
# genuine farmer meets, so it reads as the next step rather than as a failure.
REFUSALS = {
    "guest": ("You have asked several questions without signing in. "
              "Confirm your phone number to keep asking - it takes a minute."),
    "address": ("Many questions are coming from your network right now. "
                "Confirm your phone number to keep asking."),
    "daily": ("A lot of people are asking without signing in today. "
              "Confirm your phone number to keep asking."),
}
